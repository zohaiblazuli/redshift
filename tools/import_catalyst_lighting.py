"""Import the original Flare10 textures and the city4 output shader's bound inputs."""
import argparse
import gzip
from io import BytesIO
import json
from pathlib import Path
import struct
import sys

import numpy as np
from PIL import Image


TEXTURES = {
    "uCore": "gradient_col_06_clean",
    "uNoise": "gradient_col_noise",
    "uMask": "box_softedge_02",
    "uHalo": "chromaglowramp_hdr_01",
    "uRed": "T_BokehFlare",
    "uGreen": "t_circlebump_01",
    "uLookup": "lookup_circulare_02",
    "uRainbow": "polar_rainbow01",
    "uIris": "iris_disc",
}
def city4_output(root):
    # The replay job identifies the actual SRVs and constants of tonemap PS 29390603.
    job = json.loads((root / "exports/engine/skycap/city4/replay/6/job.json").read_text(encoding="utf-8"))
    draw = job["passes"][0]
    folder = root / "exports/engine/skycap/city4/textures"
    name = draw["srv"]["1"]
    cube = next(t for t in job["textures"] if t["name"] == name)
    assert (cube["format"], cube["width"], cube["height"], cube["depth"]) == ("24", 32, 32, 32)
    packed = np.fromfile(folder / f"{name}.bin", dtype="<u4").reshape(32, 32, 32)
    # R10G10B10A2_UNORM, packed into an atlas with blue slices in row-major order.
    color = np.stack([(packed >> shift) & 1023 for shift in (0, 10, 20)], axis=-1) / 1023
    color = np.concatenate((color, np.ones(color.shape[:-1] + (1,))), axis=-1)
    atlas = color.reshape(4, 8, 32, 32, 4).transpose(0, 2, 1, 3, 4)

    name = draw["srv"]["5"]
    texture = next(t for t in job["textures"] if t["name"] == name)
    assert (texture["format"], texture["srvFormat"]) == ("70", "71")
    w, h = texture["width"], texture["height"]
    raw = (folder / f"{name}.bin").read_bytes()
    header = struct.pack("<31I", 124, 0x81007, h, w, len(raw), 0, 0, *([0] * 11),
                         32, 4, int.from_bytes(b"DXT1", "little"), 0, 0, 0, 0, 0,
                         0x1000, 0, 0, 0, 0)
    dirt = np.asarray(Image.open(BytesIO(b"DDS " + header + raw)).convert("RGBA"), dtype=np.float32) / 255
    constants = bytes.fromhex(draw["cbuffers"][0]["hex"])

    def slot(index):
        return list(struct.unpack_from("<4f", constants, index * 16))

    assert slot(19)[:3] == [1.0, 1.0, 1.0]
    grade = {"size": 32, "columns": 8, "rows": 4, "coeffA": slot(22), "coeffB": slot(23),
             "colorScale": slot(12)[:3]}
    lens = {
        "dirtSize": [w, h], "bloomScale": slot(18)[:3],
        "dirtFactor": slot(20)[:3], "dirtBias": slot(21)[:3],
        "vignette": [*slot(25)[:3], slot(26)[3]],
    }
    return grade, lens, atlas.astype("<f2").tobytes(), dirt.astype("<f2").tobytes()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalyst", type=Path, help="Path to the Catalyst2Roblox checkout")
    root = parser.parse_args().catalyst.resolve()
    output = Path(__file__).resolve().parent.parent
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(root / "tools"))
    import flare_live as flare

    metadata = json.loads((flare.OUT / "flarelive.json").read_text(encoding="utf-8"))
    source = flare.fm.load_textures()
    layout, blocks = {}, []
    for uniform, name in TEXTURES.items():
        texture = source[name]
        layout[uniform] = texture["size"]
        blocks.append(texture["data"].astype("<f2").tobytes())

    grade, lens, cube, dirt = city4_output(root)
    blocks.extend((cube, dirt))
    pack = gzip.compress(b"".join(blocks), compresslevel=9, mtime=0)
    (output / "data/flare10/catalyst.bin.gz").write_bytes(pack)

    def js(name, value):
        return f"export const {name} = {json.dumps(value, indent=2)};\n"

    config = (
        "// Generated by tools/import_catalyst_lighting.py from Flare10 and city4.\n"
        "export const catalystPackUrl = new URL('../data/flare10/catalyst.bin.gz', import.meta.url).href;\n"
        + js("catalystTextureLayout", layout)
        + js("catalystLut", grade)
        + js("catalystLens", lens)
        + js("flare10Constants", metadata["constants"])
        + js("flare10Occluder", metadata["occluder"])
        + js("flare10Angles", [[*row["sun"], row["angle"]] for row in metadata["e1Angles"]])
        + js("flare10Elements", list(metadata["curves"].values()))
    )
    (output / "src/flare10.js").write_text(config, encoding="utf-8")
    print(f"Wrote {len(pack):,} compressed bytes")


if __name__ == "__main__":
    main()
